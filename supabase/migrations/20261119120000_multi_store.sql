-- Price the shelf actually charges. Sale price wins when it is a real discount.
create or replace function public.effective_price(
  p_price integer,
  p_sale_price integer,
  p_sale_pct integer,
  p_sale_start timestamptz,
  p_sale_end timestamptz,
  p_at timestamptz
) returns integer
language sql
immutable
set search_path to ''
as $$
  select case
    when p_sale_start is not null and p_at < p_sale_start then p_price
    when p_sale_end is not null and p_at > p_sale_end then p_price
    when p_sale_price is not null and p_sale_price > 0 and p_sale_price < p_price then p_sale_price
    when p_sale_pct is not null and p_sale_pct >= 1 and p_sale_pct <= 90
      then greatest(1, round(p_price * (100 - p_sale_pct) / 100.0)::integer)
    else p_price
  end;
$$;

-- products.stock stays equal to the O20 shelf so a not-yet-updated client still sees O20.
create or replace function public.sync_legacy_stock()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if new.store_id = 'O20' then
    update public.products set stock = new.shelf where id = new.product_id and stock is distinct from new.shelf;
  end if;
  return new;
end;
$$;

drop trigger if exists stock_sync_legacy on public.stock;
create trigger stock_sync_legacy
after insert or update of shelf on public.stock
for each row execute function public.sync_legacy_stock();

-- Lock the product, then the stock row, so this cannot deadlock with place_order.
create or replace function public.adjust_stock(
  p_store text,
  p_product text,
  p_op text,
  p_qty integer,
  p_shelf integer,
  p_warehouse integer,
  p_oshelf integer,
  p_owarehouse integer
) returns jsonb
language plpgsql
set search_path to ''
as $$
declare
  st public.stock%rowtype;
  v_shelf integer;
  v_wh integer;
begin
  if p_store is null or p_product is null or not exists (select 1 from public.products where id = p_product) then
    raise exception 'BAD_STOCK' using errcode = 'P0001';
  end if;
  perform 1 from public.products where id = p_product for update;
  select * into st from public.stock where store_id = p_store and product_id = p_product for update;
  if not found then
    raise exception 'BAD_STOCK' using errcode = 'P0001';
  end if;
  if p_op = 'restock' then
    if p_qty is null or p_qty <= 0 or p_qty > st.warehouse then
      raise exception 'BAD_STOCK' using errcode = 'P0001';
    end if;
    v_shelf := st.shelf + p_qty;
    v_wh := st.warehouse - p_qty;
  elsif p_op = 'receive' then
    if p_qty is null or p_qty <= 0 or p_qty >= 1000000 or st.warehouse > 1000000 - p_qty then
      raise exception 'BAD_STOCK' using errcode = 'P0001';
    end if;
    v_shelf := st.shelf;
    v_wh := st.warehouse + p_qty;
  elsif p_op = 'set' then
    if p_shelf is null or p_warehouse is null or p_oshelf is null or p_owarehouse is null
       or p_shelf < 0 or p_warehouse < 0 or p_shelf >= 1000000 or p_warehouse >= 1000000
       or st.shelf <> p_oshelf or st.warehouse <> p_owarehouse then
      raise exception 'BAD_STOCK' using errcode = 'P0001';
    end if;
    v_shelf := p_shelf;
    v_wh := p_warehouse;
  else
    raise exception 'BAD_STOCK' using errcode = 'P0001';
  end if;
  update public.stock set shelf = v_shelf, warehouse = v_wh
  where store_id = p_store and product_id = p_product;
  return jsonb_build_object('shelf', v_shelf, 'warehouse', v_wh);
end;
$$;

-- Same first five arguments as the previous function, so the current edge function
-- keeps checking out on O20 until the new one is deployed.
create or replace function public.place_order(
  p_id text,
  p_items jsonb,
  p_cash integer,
  p_bank text,
  p_proof text,
  p_store text default 'O20',
  p_email text default '',
  p_promo integer default 0
) returns jsonb
language plpgsql
set search_path to ''
as $$
declare
  it jsonb;
  pr public.products%rowtype;
  st public.stock%rowtype;
  v_total bigint := 0;
  v_cost bigint := 0;
  v_lines jsonb := '[]'::jsonb;
  v_qty integer;
  v_price integer;
  v_unit_cost integer;
  v_seq integer;
  v_num text;
  v_seen text[] := '{}';
begin
  if exists (select 1 from public.orders where id = p_id) then
    return (
      select jsonb_build_object('id', o.id, 'num', o.num, 'total', o.total, 'existing', true)
      from public.orders o where o.id = p_id
    );
  end if;
  if p_store is null or not exists (select 1 from public.stores where id = p_store and active = 1) then
    raise exception 'STOCK_CHANGED' using errcode = 'P0001';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 80 then
    raise exception 'STOCK_CHANGED' using errcode = 'P0001';
  end if;

  for it in select value from jsonb_array_elements(p_items) loop
    if (it->>'id') = any (v_seen) then
      raise exception 'STOCK_CHANGED' using errcode = 'P0001';
    end if;
    v_seen := v_seen || (it->>'id');
    select * into pr from public.products where id = it->>'id' for update;
    if not found or pr.active <> 1 then
      raise exception 'STOCK_CHANGED' using errcode = 'P0001';
    end if;
    begin
      v_qty := (it->>'qty')::integer;
      v_price := (it->>'price')::integer;
    exception when others then
      raise exception 'STOCK_CHANGED' using errcode = 'P0001';
    end;
    if v_qty is null or v_qty <= 0 or v_qty > 100000 or v_price is null then
      raise exception 'STOCK_CHANGED' using errcode = 'P0001';
    end if;
    if v_price is distinct from public.effective_price(pr.price, pr.sale_price, pr.sale_pct, pr.sale_start, pr.sale_end, pg_catalog.now()) then
      raise exception 'STOCK_CHANGED' using errcode = 'P0001';
    end if;
    select * into st from public.stock where store_id = p_store and product_id = pr.id for update;
    if not found or st.shelf < v_qty then
      raise exception 'STOCK_CHANGED' using errcode = 'P0001';
    end if;
    update public.stock set shelf = shelf - v_qty where store_id = p_store and product_id = pr.id;
    v_unit_cost := coalesce(pr.cost, 0);
    v_total := v_total + v_price * v_qty;
    v_cost := v_cost + v_unit_cost * v_qty;
    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'id', pr.id, 'name', pr.name, 'price', v_price, 'qty', v_qty, 'cost', v_unit_cost
    ));
  end loop;

  if v_total > 1000000000 or v_cost > 1000000000 or p_cash is null or p_cash < 0 or p_cash > v_total then
    raise exception 'STOCK_CHANGED' using errcode = 'P0001';
  end if;

  update public.stores set order_seq = order_seq + 1 where id = p_store returning order_seq into v_seq;
  v_num := p_store || '-' || lpad(v_seq::text, 4, '0');

  insert into public.orders (id, ts, items, total, cash, bank, proof, status, store_id, num, cost, email, promo)
  values (
    p_id, pg_catalog.now(), v_lines::text, v_total, p_cash,
    case when p_cash < v_total then coalesce(p_bank, '') else '' end,
    case when p_cash < v_total then coalesce(p_proof, '') else '' end,
    'Pending', p_store, v_num, v_cost, lower(btrim(coalesce(p_email, ''))), coalesce(p_promo, 0)
  );

  if coalesce(p_promo, 0) = 1 and btrim(coalesce(p_email, '')) <> '' then
    insert into public.subscribers (id, email, store_id, active, token)
    values (pg_catalog.gen_random_uuid()::text, lower(btrim(p_email)), p_store, 1, pg_catalog.gen_random_uuid()::text)
    on conflict (email, store_id) do update set active = 1;
  end if;

  return jsonb_build_object('id', p_id, 'num', v_num, 'total', v_total, 'cost', v_cost);
end;
$$;

